//  - 题型多样：单选/判断/填空/简答/实验/计算，避免单一换数字
//  - 每题带：分步骤解析 solution、递进 Hint1/2/3 + 完整解析L4、错因标签、变式组、来源
// 教育目标：概念→公式→题型建立联系；支撑诊断/微知识/分步训练/独立通关/错因/复测闭环

import type { QuestionType, Difficulty } from "@prisma/client";

export type Q2 = {
  key: string;                 // 幂等键（写入 source）
  node: string;                // K 级节点 code
  type: QuestionType;
  difficulty: Difficulty;
  stem: string;
  options?: string[];          // 单选：4 个选项文本，answer 为 "A"|"B"|"C"|"D"
  answer: string;
  answerNumeric?: number;
  tolerance?: number;
  steps: string[];             // 分步骤解析（考点→已知→所求→公式→运算→答案）
  hints: [string, string, string]; // Hint1方向 / Hint2关键条件 / Hint3公式框架
  errors: string[];            // 错因标签 code
  minutes: number;             // 预计时间（秒）
  tier: "原型" | "轻变式" | "情境变式";
  group: string;               // 变式组（同节点同组，复测优先）
};

// 快捷构造：减少重复代码。opts 缺省时为非选择题
export function q(
  key: string, node: string, type: QuestionType, diff: Difficulty, tier: Q2["tier"],
  stem: string, answer: string, steps: string[], hints: [string, string, string],
  errors: string[], opts?: string[], numeric?: [number, number], minutes = 45
): Q2 {
  return {
    key, node, type, difficulty: diff, tier, stem, answer, steps, hints, errors,
    ...(opts ? { options: opts } : {}),
    ...(numeric ? { answerNumeric: numeric[0], tolerance: numeric[1] } : {}),
    minutes, group: node,
  };
}

